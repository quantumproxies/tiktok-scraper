"""Row types of each command, for editors and type checkers (rows are plain dicts)."""

from typing import Any, Dict, List, Optional

try:  # Python 3.8+
    from typing import TypedDict
except ImportError:  # pragma: no cover
    from typing_extensions import TypedDict  # type: ignore


class TiktokProfileRow(TypedDict, total=False):
    """One row of `tiktok-scraper profiles` (tiktok_profile v1.0.1)."""

    platform: str
    """instagram or tiktok."""
    username: str
    """Handle."""
    user_id: Optional[str]
    """Platform-side account id."""
    full_name: Optional[str]
    """Display name."""
    biography: Optional[str]
    """Bio text."""
    verified: bool
    """Verified badge."""
    is_private: bool
    """Private account."""
    is_business: bool
    """Business/creator account."""
    category: Optional[str]
    """Account category when set."""
    external_url: Optional[str]
    """Link in bio."""
    followers: Optional[int]
    """Follower count."""
    following: Optional[int]
    """Following count."""
    posts: Optional[int]
    """Posts (Instagram) or videos (TikTok)."""
    likes: Optional[int]
    """Total likes — TikTok only, null on Instagram."""
    profile_pic: Optional[str]
    """Profile picture URL."""
    url: str
    """Profile URL."""

class TiktokVideoRow(TypedDict, total=False):
    """One row of `tiktok-scraper videos` (tiktok_video v1.1.1)."""

    rank: int
    """1-based delivery order."""
    video_id: str
    """TikTok video id."""
    url: str
    """Video URL."""
    description: Optional[str]
    """Caption."""
    created_at: Optional[str]
    """Publish time (ISO 8601)."""
    author: Optional[str]
    """Author handle."""
    author_name: Optional[str]
    """Author display name."""
    author_id: Optional[str]
    """Author id."""
    author_verified: bool
    """Author verified badge."""
    author_followers: Optional[int]
    """Author follower count."""
    views: Optional[int]
    """Play count."""
    likes: Optional[int]
    """Like count."""
    comments: Optional[int]
    """Comment count."""
    shares: Optional[int]
    """Share count."""
    saves: Optional[int]
    """Save/collect count."""
    duration_seconds: Optional[int]
    """Duration in seconds."""
    music: Optional[str]
    """Music title."""
    music_author: Optional[str]
    """Music author."""
    hashtags: List[str]
    """Hashtags in the caption."""
    cover: Optional[str]
    """Cover image URL."""
    mentions: List[str]
    """Accounts mentioned in the caption."""
    reposts: Optional[int]
    """Repost count."""
    author_following: Optional[int]
    """Accounts the author follows."""
    author_likes: Optional[int]
    """Total likes on the author's videos."""
    author_videos: Optional[int]
    """Videos published by the author."""
    author_signature: Optional[str]
    """Author bio."""
    music_id: Optional[str]
    """TikTok sound id."""
    music_original: Optional[bool]
    """True when the sound is the author's original."""
    location_created: Optional[str]
    """Country the video was posted from."""
    language: Optional[str]
    """Caption language."""
    width: Optional[int]
    """Video width (px)."""
    height: Optional[int]
    """Video height (px)."""
    is_ad: bool
    """Marked as an ad."""
    ai_generated: bool
    """Labelled AI-generated by TikTok."""
    duet_enabled: Optional[bool]
    """Duets allowed."""
    stitch_enabled: Optional[bool]
    """Stitches allowed."""
    is_photo_post: bool
    """Photo carousel rather than a video."""
    subtitle_languages: List[str]
    """Subtitle languages available."""
    related_searches: List[str]
    """Searches TikTok suggests next to the video."""
